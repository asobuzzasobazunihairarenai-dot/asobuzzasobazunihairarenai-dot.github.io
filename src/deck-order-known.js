// 🔴【#724 の続き・続き791】「山札の並びが分かり得るか」を1か所で持つ。
//
// ユーザー判断（2026-11-21）:
//   「山札から複数マスに置く場合で、**山札の中の順番が全くわからない状態の時は、
//     置く順番を選ぶ必要はないので自動でいい**と思います！
//     山札切れで捨て場ノーシャッフルで山札になった以降や、今後山札の中身を見る効果の
//     カードが使用された時などは、山札からカードを置く時に順番が大事になると思います！」
//
// ⇒ **分からない時は聞かない**（手間だけ増えるので）。**分かり得る時だけ聞く。**
//
// 【いまのところ「分かり得る」のはこの1つだけ】
//   ・山札が切れて、**捨て場をそのまま裏返して**山札にした（ノーシャッフル）。
//     捨て場は誰でも中身と順番を見られる（捨て札一覧）ので、**以降は並びが分かり得る**。
//
// 【これは state に入れていない】
//   🔴 オンラインでは state はサーバーから来るので、クライアントが足した欄は
//     `hydrateState` で**丸ごと消える**。state に入れるなら
//     `supabase/functions/so7-apply-action.ts` にも同じものが要る＝**再デプロイが必要**になる。
//     見た目（聞くか聞かないか）の話なので、**クライアントのローカルな記録**で足りる。
//   ⚠ そのため**読み込み直すと忘れる**（＝聞かなくなる）。安全側に倒してある
//     （聞かなければ自動で置くだけで、盤面は正しい）。
//   ⚠ オンラインでは、入れ替わりの瞬間を見逃すと忘れたままになる（同上）。
//
// 【他のモジュールを import しない葉】state.js から呼ぶので、循環させないため。

let 分かり得る = false;

// 山札の並びが分かり得る状態になった（理由は呼ぶ側が持つ）。
// 将来「山札の中身を見る」効果を足したら、そこからもこれを呼ぶ。
export function noteDeckOrderKnown() {
  分かり得る = true;
}

// 新しい対局が始まったら忘れる。
export function forgetDeckOrderKnown() {
  分かり得る = false;
}

export function isDeckOrderKnown() {
  return 分かり得る;
}

// 山札・捨て場の枚数の「前」と「後」から、ノーシャッフルの入れ替わりが起きたかを見る。
// ⚠ 山札が空になった**その瞬間に**捨て場が山札へ移る（state.js の DRAW_FROM_PILE は
//   引く処理の中で原子的に補充する）ので、「前は山札0・捨て場あり → 後は山札あり」で拾える。
//   REFILL_DECK_FROM_DISCARD（単独の補充）も同じ形になる。
export function noteDeckPilesChanged(前, 後) {
  if (!前 || !後) return;
  const 前山 = (前.deck || []).length;
  const 前捨 = (前.discard || []).length;
  const 後山 = (後.deck || []).length;
  if (前山 === 0 && 前捨 > 0 && 後山 > 0) noteDeckOrderKnown();
}
