// 色者の円盤（移動先表示）の**唯一の持ち主**。
//
// ■ これは何か
//   【色者】のカードは、各プレイヤーのターン終了時に山札から1枚捨て、その色（捨色）の
//   向きへ1マス動く。その「どの色がどの向きか」を示すのが、カードの絵に描かれた円盤。
//
// ■ 🔴 絵は SVG（2026-11-20・ユーザー判断「以前のSVGの八角形をとりあえず採用しよう!」）
//   続き766 で本物のカードの画素を測って起こしたもの。続き767 で「切り抜きの方が近い」と
//   判断して一度消したが、並べて見てもらって**こちらを採る**ことになった（git から戻した）。
//   ⚠ SVG なのでどの大きさでもにじまず、画像のように「幅×高さ×4バイト」のメモリを食わない（#223）。
//   ⚠ 線が**白**なので、**置く側で暗い地を敷くこと**（明るい地に素で置くと線が消える）。
//     カードの絵の上に置く時は、絵そのものが地になる。
//
// ■ 並びは**リメイク版（新版）**（続き765・766 のユーザー裁定と実測）
//   上=緑 ／ 右上=青 ／ 右=桃 ／ 右下=紫 ／ 左下=赤 ／ 左=橙 ／ 左上=黄。
//   真下は切り欠き（無色は動かない）。虹はそのターンのプレイヤーが周囲8マスから選ぶ。
//   ⚠ 動きの表そのものは `src/main.js` の `SHIKIJA_DIRS`。**絵と表は別物なので、
//     どちらかを直したらもう一方も見ること**（続き765 で表だけ直して絵が残った）。
//   ⚠ 旧0th拡張の印刷カードの円盤は**左右が逆**。アプリは新版に合わせてある。

export const SHIKIJA_DIAL_SRC = "assets/icons/shikija-dial.svg";

// 円盤が描かれているカード（＝【色者】を持つカード）。増えたらここに足す。
export const CARDS_WITH_SHIKIJA_DIAL = new Set(["ex0-white-dragon"]);

export function hasShikijaDial(cardId) {
  return CARDS_WITH_SHIKIJA_DIAL.has(cardId);
}
