// ONLY の印（印刷カードの左下…ではなく**絵の真ん中**に入っている2段の文字組み）。
//
// ■ これは何か
//   ONLY カードには、絵の上に**色の名前**が大きく字間を広げて入り、その下に **ONLY** が
//   小さくさらに広い字間で中央に入っている（例: `W H I T E` ／ `O N L Y`）。
//   「1種類に1枚しか入れられない札」であることの印。
//
// ■ 🔴 絵ではなく**文字**で起こす（続き766 の方針）
//   トレースして画像にすると ①7色ぶんの画像が要る ②拡大でにじむ
//   ③画像は「幅×高さ×4バイト」でメモリを食う（#223）。
//   文字で組めば**1つの仕掛けで10色ぶん**出せて、どの大きさでもにじまず、メモリを食わない。
//
// ■ 寸法は**実測から**決めた（scratchpad/_only_measure.mjs・目で読まない＝続き766 の教訓）
//   元は `D:/Adobe退避/SOSC_通常カード_表_only１.png`（650px角・2026.11・かくざとうさん）。
//   背景が白い龍なので一律のしきい値では字と地が分かれない ⇒ 拾った塊を
//   「すきま 12px 未満なら1字」とまとめて割った（字の間は実測 55px 以上ある）。
//
//   | | 実測（650px角のカードの上で） |
//   |---|---|
//   | 色の名前 | 字の高さ **21px** ／ 1字の送り **73.5px** ／ 全幅 306px |
//   | ONLY | 字の高さ **10px** ／ 1字の送り **36.3px** ／ 全幅 115px |
//   | 比 | 大きさ **0.476** ／ 送り÷字高 **3.50**（色）と **3.63**（ONLY） |
//   | 行の間 | 色の名前の地 → ONLY の天 = **21px**（＝色の名前の字高ちょうど1つぶん） |
//   | 中心 | 2段とも**同じ軸**（ずれ 3.5px。しきい値で右が少し欠けたぶん） |
//
// ■ ⚠ 書体について（1pxまで同じにはならない）
//   印字の書体は **W の墨幅 ÷ 字高 = 1.52** ／ **H = 0.91** という**幅の広い**グロテスク
//   （手元で測った中では Verdana Bold がいちばん近い）。
//   🔴 ただし Verdana は Windows と Mac にしか無い＝**端末ごとに見た目が変わる**（#453・#569 の家族）。
//   ⇒ **index.html が全員に読ませている Noto Sans JP の 900** を使う。W/字高 = 1.20 と
//     印字より細いが、1字の送りが字高の 3.5倍もあるので**字の幅の差は送りの1割未満**＝
//     並びの印象は変わらない。**どの端末でも同じ見た目になる方を採った。**
//   ⓘ 1pxまで合わせたくなったら、かくざとうさんに書体名を聞く（円盤のベクターと同じ話）。
//
// ■ ⚠ `letter-spacing` は**最後の字の後ろにも**空きを入れる
//   そのまま中央寄せすると、墨の中心が空きの半分だけ左へずれる。
//   ⇒ 同じ値の `margin-right` を負で足して打ち消す（CSS 側）。

// 色 → 印字の欧字。**ここが唯一の持ち主**（パックの画面もここから読む。
// 2か所に書くと必ず食い違う＝続き762 の教訓）。
export const COLOR_WORD = {
  red: "RED", orange: "ORANGE", yellow: "YELLOW", green: "GREEN",
  blue: "BLUE", pink: "PINK", purple: "PURPLE",
  rainbow: "RAINBOW", white: "WHITE", black: "BLACK",
};

// ONLY の印を1つ作って返す。`color` を知らない時は "SEVEN"（パックの画面の控えと同じ）。
// ⚠ 組み立てはこの関数**1つだけ**。置く所が増えても見た目は1か所で決まる。
//
// 🔴 `色名を出す: false` は「**色の名前が既にそこに在る**」時のため（2026-11-20・続き772）。
//   0th拡張の絵には色の名前が**焼き込まれている**（素材の5層目。実測で20枚とも同じ位置）。
//   その絵の上に印を置くなら、こちらが出すのは **ONLY の行だけ**——色の名前を重ねると二重になる。
//   ⚠ 絵の中の字は読み上げに乗らないので、**色の名前は aria-label に残す**（見た目から消すだけ）。
export function buildOnlyMark(color, { 色名を出す = true } = {}) {
  const 語 = COLOR_WORD[color] || "SEVEN";
  const box = document.createElement("div");
  box.className = "only-mark";
  if (色名を出す) {
    const 色 = document.createElement("span");
    色.className = "only-mark-color";
    色.textContent = 語;
    box.appendChild(色);
  } else {
    box.setAttribute("aria-label", 語 + " ONLY");
  }
  const 印 = document.createElement("span");
  印.className = "only-mark-only";
  印.textContent = "ONLY";
  box.appendChild(印);
  return box;
}
