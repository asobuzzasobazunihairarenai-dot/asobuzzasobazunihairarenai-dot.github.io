// 1st EDITION の駒「◯のジュエル」の**本物の立体**（WebGLで描く宝石の形）。
//
// 【なぜ立方体ではないのか】
// ユーザーの問い「そもそも立方体ではなくジュエルの形状はできますか？」→ 判断
// 「WebGLで本物の立体にする」。駒の見た目は board-3d.js（three.js）が描いているので、
// **DOMの立方体の5面を板で描く代わりに、八角形のブリリアントカットの立体を1つ描く**。
// DOMの立方体（.piece / .piece-face）は**当たり判定の箱として残す**——このアプリの
// タップ判定は elementsFromPoint による自前方式（教訓4）なので、箱を消すと掴めなくなる。
//
// 【ここに置く理由】import を1つも持たない葉にしておく（three.js だけ）。
// board-3d.js から読むだけなので循環しない（続き573 の TDZ 対策）。
//
// 【形】駒の箱（幅 w × 奥行き h × 高さ H）にぴったり収まる、8回対称の宝石。
//   ・天面（テーブル面）＝平らな八角形
//   ・クラウン（天面〜ガードル）＝16面。隣の輪を 22.5度 ずらしてあるので**三角のファセット**になる
//     （本物のブリリアントカットと同じ作り。四角い面を並べるより宝石らしく見える）
//   ・ガードル＝いちばん広い所。正八角形が駒の正方形にちょうど内接する
//   ・パビリオン（ガードル〜底）＝16面。**ここが深い**（絵と同じ）。底は小さな八角形に
//     切ってあり、盤に平らに接する（絵では尖っているが、尖ったままでは駒が立たない）
//   合計 44 枚の三角形＝132 頂点（天面6＋クラウン16＋パビリオン16＋底面6）。
//
// 🔴 【陰影は「立方体のCSSと同じ式」で付ける】
//   立方体の壁は CSS の filter: brightness() で陰影を付けている
//   （手前 1.0 / 右 0.8 / 左 0.55 / 奥 0.35 / 上面 1.0）。宝石のファセットは向きが
//   連続的に変わるので、**この5点をちょうど通る線形の式**を解いて使う:
//     b(n) = 0.675 + 0.125*nx - 0.325*ny + 0.325*nz
//   （右/左から base=0.675・kx=0.125、手前/奥から ky=0.325、上面から kz=0.325。
//     5点とも誤差なく一致する＝目分量ではない）。
//   これに「きらめき」（上かつ手前を向いたファセットだけ強く光る）を足す。
//   ⇒ ふだんの駒と**同じ光の向き**に見えるので、同じ盤の上で違和感が出ない。
//
// 🔴 【色は素材から測った値】ジュエルの素材（PV・説明書(1st)の jewel_<色>.png）の
//   不透明な画素の**中央値**。測り方は scratchpad/_jewelcol.mjs（道具は
//   tools/make-jewel-pieces.mjs と同じ素材を見る）。素材を描き直したら測り直す。
import * as THREE from "../vendor/three.module.min.js";

// 宝石そのものの色（sRGB 0-255）。上記のとおり素材の中央値。
export const JEWEL_BODY_RGB = {
  red: [250, 55, 55],
  orange: [255, 137, 69],
  yellow: [255, 211, 69],
  green: [103, 183, 89],
  blue: [88, 149, 224],
  pink: [243, 105, 154],
  purple: [172, 123, 199],
};

// --- 形を決める値 ---------------------------------------------------------------------
// 🔴 【いちばん大事・形を3回やり直して分かったこと】
//    **斜め上から見下ろすと、宝石の下のとがり（パビリオン）は見えないのが正しい。**
//    盤面の傾きは `--table-tilt: 42deg` ＝ 盤から **48度** の高さから見ている。
//    PV（1st EDITION 紹介動画）のジュエルの横顔が見えるのは **PVのカメラが低いから**で、
//    48度から見れば下半分はガードル（いちばん広い所）の陰に隠れる。
//
//    上から見てパビリオンの面が見えてしまう条件は、外向き法線がカメラの向き
//    d=(0,-0.669,+0.743) と同じ側を向くこと。法線は（半径方向, z）で (Hp, -Rg) に
//    比例するので:
//        Hp * 0.669 > Rg * 0.743   ⇔   **Hp > 1.11 * Rg**（＝見えてしまう）
//    （Hp＝ガードルから底までの高さ、Rg＝ガードルの半径。どちらも実寸）
//    ⇒ **本物の宝石の比（Hp ≒ 0.84 * Rg）なら、この式を満たさない＝ちょうど隠れる。**
//
//    ⚠ **やり直した3回（同じ所を2度まちがえた）**
//      1回目: ガードルを下から 0.4（＝上下が逆・クラウンが高い「テント」）
//              → 「ジュエルが横向きになってるように感じます」
//      2回目: 絵から測って 0.66。Hp/Rg = 1.26 で上の式を**わずかに超えていた**
//              → とがりが薄い影にしかならず「尖りが手前側面方向に向いて見える」
//      3回目: とがりを**見せよう**として Hp/Rg = 1.94 にした ← 🔴 **向きが逆の直し**
//              → 「本来尖りは見えないはずなので、見えているのが不自然」（そのとおり）
//      いま: **本物の宝石の比**（Hp/Rg = 0.84）。とがりは隠れ、上から見た宝石になる。
//
// 🔴 **宝石の比率は決まっているので、高さは「駒の高さ」ではなく「駒の幅」から決める。**
//    本物のブリリアントは 深さ ≒ 直径の 0.6。だから駒の幅が 2.1rem なら宝石の高さは
//    約 1.25rem ＝ **立方体の駒（2rem）より低い**。これは宝石がそういう形だからで、
//    低くしたくて低くしているのではない。`--piece-height` を変えても宝石は変わらない。
//
// 🔴 比率の出どころは PV のジュエルの絵（scratchpad/_jewelshape.mjs で実測。4色とも
//    ガードルは下から 56〜58%・高さ÷幅 0.88。⚠ 絵は遠近つきなので画面の縦には天面の
//    奥行きが足されている）と、本物のブリリアントカットの寸法。
//
// 相対半径（1.0 ＝ 駒の幅のちょうど半分。正八角形が駒の正方形にちょうど内接する大きさ）
const R_TABLE = 0.55; // 天面（ガードル径の 0.55＝本物のブリリアントと同じ）
const R_GIRDLE = 1.0; // ガードル（いちばん広い）
const R_BASE = 0.04; // 底。ほぼ一点（0にすると面積0の三角が出るので、ごく小さく残す）
// 高さ（**駒の幅** を 1 とした時）。Rg = 0.5 なので、下は 0.84*Rg、上は 0.35*Rg。
const Z_BASE = 0;
const Z_GIRDLE = 0.42;
const Z_TOP = 0.595;

/** 宝石の高さ（駒の幅を 1 とした時）。board-3d.js が並べ替えの鍵に使う。 */
export const JEWEL_TOP_Z = Z_TOP;

// 🔴 面の輪郭線（絵と同じ「線で囲まれた宝石」の見た目）。
//    上から見下ろすこのカメラでは**天面とクラウンしか見えない**ので、線が無いと
//    ただの多面の丘＝「傘」に見える。線は、面いっぱいを濃い色で塗ってから
//    内側だけを面の色で塗り直すことで作る（下の 面を置く を参照）。
// 【#550・2026-11-11】ユーザー報告「カットの線が太すぎるかも？」→「一旦半分に！」で 0.022 → 0.011。
const EDGE_WIDTH = 0.011; // 線の太さ（駒の幅を 1 とした長さ）
const EDGE_DARK = 0.34; // 線の濃さ（その面の色に掛ける）

const N = 8; // 8回対称
const STEP = (Math.PI * 2) / N;
const HALF = STEP / 2; // 輪を半ステップずらすと三角のファセットになる

// きらめきの光の向き（正規化済み。上＋手前）。下の座標系で書いてある。
const SPARK = [0.25, 0.62, 0.745];

/**
 * ファセット1枚の明るさ。立方体のCSSの陰影をちょうど通る式＋きらめき。
 * n は正規化済みの外向き法線。
 *
 * 🔴 **座標系は style.css の transform から読み取ったもの**（推測ではない）:
 *      手前の壁 `.piece-wall-front` は `rotateX(-90deg)` ⇒ 法線 **(0, +1, 0)**・明るさ 1.0
 *      奥の壁   `.piece-wall-back`  は `rotateX(90deg)…`  ⇒ 法線 (0, -1, 0)・明るさ 0.35
 *      右の壁                                            ⇒ (+1, 0, 0)・0.8
 *      左の壁                                            ⇒ (-1, 0, 0)・0.55
 *      上面                                              ⇒ (0, 0, +1)・1.0
 *    ＝ **+y は「手前（プレイヤー側）」で、そちらが明るい**。
 *    ⚠ 最初これを逆に（-0.325*ny と）書いていて、**宝石だけ手前が暗く奥が明るい**という、
 *      立方体の駒と逆の当たり方になっていた（続き677）。気づけなかったのは、
 *      **同時に表裏も裏返っていて宝石の内側を見ていたから**——2つの間違いが
 *      重なると、どちらにも気づけない。**1つずつ、白く塗る等の決まった値で確かめる。**
 */
export function jewelFacetShade(nx, ny, nz) {
  // 🔴 下を向くファセット（nz<0）は立方体に**存在しない**向きなので、5点の縛りが掛からない。
  //    素直に -0.325*|nz| にすると、パビリオン（下半分）がほぼ真っ黒になり、
  //    盤の上で見ると駒全体が黒ずんで見えた（実測で確かめた）。宝石は内部で光が回るので、
  //    下向きの面は**浅く**落とす。上向き（nz>0）は立方体の上面と同じ 0.325 のまま。
  const kz = nz >= 0 ? 0.325 * nz : 0.1 * nz;
  let b = 0.675 + 0.125 * nx + 0.325 * ny + kz;
  const d = nx * SPARK[0] + ny * SPARK[1] + nz * SPARK[2];
  if (d > 0) b += 0.5 * Math.pow(d, 6);
  // 下限は立方体のいちばん暗い面（奥の壁 0.35）と同じ——駒がそれより黒くならないように。
  // 上限は白飛びしない所で止める。
  return Math.max(0.35, Math.min(1.28, b));
}

// --- 立体を組む -----------------------------------------------------------------------
// 単位の箱の中で組む: x,y ∈ [-0.5, 0.5]（あとで w, h を掛ける）、z ∈ [0, 1]（H を掛ける）。
// ⇒ 底が z=0（盤に接する）、天面が z=H。
function ring(r, z, offset) {
  const out = [];
  for (let i = 0; i < N; i++) {
    const a = i * STEP + offset;
    out.push([Math.cos(a) * r * 0.5, Math.sin(a) * r * 0.5, z]);
  }
  return out;
}

const _c = new THREE.Color();

function buildGeometryFor(rgb) {
  const 天 = ring(R_TABLE, Z_TOP, HALF);
  const 腰 = ring(R_GIRDLE, Z_GIRDLE, 0);
  const 底 = ring(R_BASE, Z_BASE, HALF);

  // --- 面（多角形）の一覧 -----------------------------------------------------------
  // 🔴 **三角ではなく「面」で持つ。** 天面と底面は八角形1枚で、扇に割った内側の線は
  //    輪郭線として描いてはいけない（平らな天面に線が入ってしまう）。
  const 面 = [];
  面.push(天.slice()); // 天面（八角形1枚）
  // クラウン: 天の頂点は腰の i と i+1 のあいだに在る（半ステップずれているため）
  for (let i = 0; i < N; i++) {
    const j = (i + 1) % N;
    面.push([天[i], 腰[i], 腰[j]]); // 下を向く三角
    面.push([腰[j], 天[i], 天[j]]); // 上を向く三角
  }
  // パビリオン: 同じ組み方で腰→底
  for (let i = 0; i < N; i++) {
    const j = (i + 1) % N;
    面.push([底[i], 腰[j], 腰[i]]);
    面.push([腰[j], 底[i], 底[j]]);
  }
  面.push(底.slice()); // 底面（ふだん見えないが、閉じていないと横から覗いた時に穴が開く）

  // 外へ向いているかの判定に使う内側の1点（軸上・ガードルの高さ）
  const 内 = [0, 0, Z_GIRDLE];

  // 面ごとに「外向きの法線・明るさ・巻き方をそろえた頂点」を先に出しておく。
  const 整えた = 面.map((poly) => {
    const p = poly.map((v) => v.slice());
    const c = [0, 0, 0];
    for (const v of p) { c[0] += v[0]; c[1] += v[1]; c[2] += v[2]; }
    c[0] /= p.length; c[1] /= p.length; c[2] /= p.length;
    // 法線はニューウェル法（頂点が3つより多い面でも安定する）
    let nx = 0, ny = 0, nz = 0;
    for (let i = 0; i < p.length; i++) {
      const a = p[i], b = p[(i + 1) % p.length];
      nx += (a[1] - b[1]) * (a[2] + b[2]);
      ny += (a[2] - b[2]) * (a[0] + b[0]);
      nz += (a[0] - b[0]) * (a[1] + b[1]);
    }
    const len = Math.hypot(nx, ny, nz) || 1;
    nx /= len; ny /= len; nz /= len;
    // 外向きでなければ、法線と**巻き方の両方**を裏返す
    // （巻き方をそろえておかないと、裏面を捨てる描き方ができない）。
    if (nx * (c[0] - 内[0]) + ny * (c[1] - 内[1]) + nz * (c[2] - 内[2]) < 0) {
      nx = -nx; ny = -ny; nz = -nz;
      p.reverse();
    }
    return { p, c, 明: jewelFacetShade(nx, ny, nz) };
  });

  const 三角の数 = 整えた.reduce((n, f) => n + (f.p.length - 2), 0) * 2; // 輪郭＋内側の2枚重ね
  const pos = new Float32Array(三角の数 * 9);
  const col = new Float32Array(三角の数 * 9);
  let o = 0;
  const 置く = (v) => {
    pos[o] = v[0]; pos[o + 1] = v[1]; pos[o + 2] = v[2];
    col[o] = _c.r; col[o + 1] = _c.g; col[o + 2] = _c.b;
    o += 3;
  };
  const 面を置く = (f, 細め, 濃さ) => {
    // 🔴 sRGB で測った色に係数を掛けてから、three.js の作業色空間（リニア）へ渡す。
    //    リニアのまま掛けると CSS の brightness() と意味が変わる（続き420 で踏んだ話）。
    _c.setRGB(
      Math.min(1, (rgb[0] / 255) * f.明 * 濃さ),
      Math.min(1, (rgb[1] / 255) * f.明 * 濃さ),
      Math.min(1, (rgb[2] / 255) * f.明 * 濃さ),
      THREE.SRGBColorSpace
    );
    // 🔴 中心へ**決まった長さ**だけ寄せる（割合ではない）。割合で寄せると大きい面ほど
    //    線が太くなり、天面だけ縁が分厚く見える。線の太さは絵と同じでそろえたい。
    const v = f.p.map((q) => {
      const dx = f.c[0] - q[0], dy = f.c[1] - q[1], dz = f.c[2] - q[2];
      const d = Math.hypot(dx, dy, dz) || 1;
      const t = Math.min(細め / d, 0.45); // 小さい面でも中心を越えない
      return [q[0] + dx * t, q[1] + dy * t, q[2] + dz * t];
    });
    for (let i = 1; i < v.length - 1; i++) { 置く(v[0]); 置く(v[i]); 置く(v[i + 1]); }
  };
  // 🔴 **先に輪郭の色で面いっぱいを、次に内側だけを面の色で塗る**＝外にはみ出した分が線になる。
  //    この描き方なら**深度バッファが無くても線が突き抜けない**（このアプリは描く順番だけで
  //    前後を決めている）。ただの平らな三角が2枚重なっているだけだから。
  //    ⚠ 立体は凸なので、手前を向いた面どうしが画面で重なることは無い＝この2枚重ねで正しい。
  for (const f of 整えた) 面を置く(f, 0, EDGE_DARK);
  for (const f of 整えた) 面を置く(f, EDGE_WIDTH, 1);
  const geo = new THREE.BufferGeometry();
  geo.setAttribute("position", new THREE.BufferAttribute(pos, 3));
  geo.setAttribute("color", new THREE.BufferAttribute(col, 3));
  return geo;
}

// 色ごとに1つ作って使い回す（7個で止まる）。
const cache = new Map();

/** 色名（red/orange/…）から宝石の立体を返す。知らない色なら null。 */
export function getJewelGeometry(color) {
  const rgb = JEWEL_BODY_RGB[color];
  if (!rgb) return null;
  let geo = cache.get(color);
  if (!geo) {
    geo = buildGeometryFor(rgb);
    cache.set(color, geo);
  }
  return geo;
}

/** 面の数（検査・ログ用） */
export function getJewelFacetCount() {
  // 三角の数: 天面 6 ＋ クラウン 16 ＋ パビリオン 16 ＋ 底面 6 ＝ 44。
  // ⚠ 実際の立体はこれを**2枚重ね**にしてある（輪郭線のため）＝ 88 三角・264 頂点。
  //    面（多角形）としては 天1＋クラウン16＋パビリオン16＋底1 ＝ 34 枚。
  return (N - 2) * 2 + N * 4;
}
