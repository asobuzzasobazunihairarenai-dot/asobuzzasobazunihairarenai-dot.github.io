// 🔴【2026-11-28・続き883】**ノワールのお試し（期間限定）。**
//
// ■ これは何か
//   ユーザー案「期間限定で、ゲームプレイ時ファーストカードが配られた後に
//   『ノワールに切り替えますか？』的なモーダルを出し、ノワールを使用できるようにしよう」。
//
// ■ 🔴 仕掛けは**もう在った**
//   `state.js` の `applySeatNoir(seat, brands)` が、その席について
//   ①ファーストカードを `first-noir` に差し替え ②駒を黒に ③ブーストの白紙を取り除く
//   まで一式やる（エイドス物語戦とマイデッキの黒で既に使っている道）。
//   ⇒ 新しく作るのは**聞く所と、期間の決まり**だけ。
//
// ■ ⚠ いまは **CPU戦・ローカル対戦だけ**
//   オンラインは**サーバー（Edge Function）が配る**ので、こちらで差し替えると盤面がずれる。
//   オンラインにも出すなら `APPLY_SEAT_NOIR` をサーバー側にも足して**再デプロイ**が要る。
//   （マイデッキの黒は、配る前にサーバーへ「黒で」と伝える形なので別の道。
//     あちらは `SELECTABLE_FIRST_COLORS` で受けている＝続き2026-11-04）
//
// ■ 期間
//   🔴 **終わりの日はここ1行**。過ぎると聞かれなくなる（コードは残るので、日付を伸ばすだけで戻る）。
//   ⚠ 日付は**端末の時計**で見る。ずれている端末では早く終わる／長く出るが、
//     お試しなので実害は無い（勝敗にも持ち物にも触らない）。
export const NOIR_TRIAL_UNTIL = "2026-12-31";

// お試しの期間内か。
export function isNoirTrialOpen(now = new Date()) {
  try {
    // その日の終わりまで（= 終わりの日も丸ごと含む）。
    const 終 = new Date(NOIR_TRIAL_UNTIL + "T23:59:59");
    return now.getTime() <= 終.getTime();
  } catch (err) {
    return false;
  }
}

// この対局で聞くべきか。
// ⚠ **もうノワールで始まる時は聞かない**（マイデッキで黒を選んでいる＝二度手間）。
// ⚠ 物語チュートリアル（相手がノワール）でも聞かない——あちらは台本どおりに進む対局。
export function shouldOfferNoir({ 期間内 = isNoirTrialOpen(), 既に黒 = false, 台本 = false } = {}) {
  return !!期間内 && !既に黒 && !台本;
}
