// 🔴🔴【#805 / #808・続き827】不具合報告が**丸ごと届かなくなる**罠を見張る（27本目）。
//
// 何が起きたか:
//   報告の中に「**絵文字の片割れ**」（対になっていないサロゲート）が1文字でも混ざると、
//   サーバーの JSON 読み取りが **本文ごと** 弾く（PGRST102 "Empty or invalid json"）。
//   本番で実証した——`"📋サマリー".slice(0, 1)` を送ると弾かれ、掃除すると通る。
//   ⇒ **墜落の記録が2回まるごと失われた**（#805 #808）。いちばん欲しい時に届かない。
//
// なぜ起きるか:
//   画面の記録（context）は DOM の文字を `.slice(0, N)` で切って集める。
//   アプリのボタンは 📋 ⏭ 🔔 🪙 🃏 だらけなので、**切る位置が絵文字の真ん中に当たる**。
//
// ここで見るもの（どれか1つでも崩れたら、また静かに届かなくなる）:
//   ① 深い所の文字列まで掃除される（context は object の中に何十本も文字列を持つ）
//   ② **切ったあとに**もう一度掃除される（切る処理は文字の単位なので、片割れが生まれ直す）
//   ③ ちゃんとした絵文字は消さない（掃除しすぎていないか）
//   ④ 検出器が**生の文字列**を見ている（JSON.stringify してから探すと永久に見つからない
//      ＝実際にそう書いて、0しか出ない検査になっていた）
import { 送れる形に整える, 中まで掃除する, 片割れが残っているか } from "../src/bug-payload.js";

const NG = [];
const 行 = (名, 可, 実) => {
  if (!可) NG.push(名 + (実 === undefined ? "" : "  " + JSON.stringify(実)));
  console.log((可 ? "  ✅ " : "  ❌ ") + 名);
};

console.log("── 不具合報告の中身（絵文字の片割れで丸ごと弾かれないか）──");

// ④ 検出器そのものが働くか（これが嘘だと、以下が全部「0しか出ない検査」になる）
const 片 = "📋".slice(0, 1);
行("検出器が、絵文字の片割れを見つける", 片割れが残っているか({ a: 片 }) === true);
行("検出器が、ちゃんとした絵文字を誤検出しない", 片割れが残っているか({ a: "📋サマリー" }) === false);

// ① 深い所まで
const 深い記録 = { a: { b: [{ c: 片 }] }, ok: "📋", n: 1, z: null };
行("対照: 掃除する前は片割れが在る", 片割れが残っているか(深い記録) === true);
行("中まで掃除すると、深い所の片割れも消える", 片割れが残っているか(中まで掃除する(深い記録)) === false);
行("数字・null はそのまま", (() => { const o = 中まで掃除する(深い記録); return o.n === 1 && o.z === null; })());
行("③ ちゃんとした絵文字は残る", String(中まで掃除する(深い記録).ok) === "📋");

// ②（切ったあとに生まれ直す形）: 絵文字をちょうど境目に置いて、切らせる。
const 長いログ = "あ".repeat(400000) + "🃏";
const r = 送れる形に整える({
  comment: "テスト" + 片,
  actionLog: 長いログ,
  consoleLog: "警告" + 片,
  context: 深い記録,
});
行("送る形の全体に、片割れが1つも残っていない", 片割れが残っているか(r) === false, r.内訳);
for (const k of ["comment", "action_log", "console_log", "context"]) {
  行("　・" + k + " に残っていない", 片割れが残っているか(r[k]) === false);
}
行("送る側が自分でも気づけるようにしてある（印の欄がある）", !r.内訳.壊れた文字が残った);

if (NG.length) {
  console.log("\n🔴 問題 " + NG.length + " 件");
  for (const n of NG) console.log("  ・" + n);
  process.exitCode = 1;
} else {
  console.log("✅ 問題なし（絵文字の片割れは、送る前に必ず落ちる）");
}
