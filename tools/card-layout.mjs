// 焼き出した4枚を、**この順に**、それぞれの合成モードで重ねる。
//
// 🔴 **当てずっぽうではなく、本物と突き合わせて選んだ。**
//  ① 階調と肌理（紫１・0〜255の平均差）
//     全部「そのまま」                  → 48.1
//     **階調=オーバーレイ・肌理=乗算**  → **8.7**（最小）
//     影も乗算にする                    → 12.0（悪くなる）
//  ② 影（下のパネル）は **別立てにして、枠の「後」に「カラー」で重ねる**。
//     最初は normal に混ぜて「そのまま」重ねていたが、**緑や黄のカードで下のパネルが
//     白っぽく抜けた**（本物は地の色が透けている）。
//     🔴 1点を1段ずつ測って原因が割れた: **枠（Over）に入っている白いパネルが
//       不透明度 75.7% で後から被さり、下の色を消していた。**
//       だから影を先に置いても意味がなく、**影は枠の後に置いて色を乗せる**のが正しい。
//       .ai のレイヤーの並びでも Over が先・Shadow が後になっている。
//     6枠（緑・黄・紫・赤・青・白）で順番と重ね方を総当たりした結果（全体の平均）:
//       影が後・soft-light  12.77   影が後・**カラー**  **12.80**
//       影が後・overlay     13.14   影が先・カラー      13.15
//       影が後・hue         13.96   影が後・saturation  16.05
//       影が後・そのまま    24.15   影が後・乗算        28.29
//     ⚠ soft-light とカラーは**ほぼ互角**（0.03差）。.ai が実際に指定しているのが
//       「カラー50%＋乗算50%」なので、根拠のある**カラー**を採った。
//       いちばん効いたのは黄のカードで、18.27 → 12.07。
export const BAKE_ORDER = ["normal", "shadow", "grad", "tex"];
export const BAKE_BLEND = { normal: null, shadow: "color", grad: "overlay", tex: "multiply" };

