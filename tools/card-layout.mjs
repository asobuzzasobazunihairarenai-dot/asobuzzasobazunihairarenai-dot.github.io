// 🔴 **ここに集めた理由**: make-card.mjs（組み立て）と verify-card-art.mjs（確かめ）の
//   両方が同じ値を使う。片方だけ直すと、**確かめる側が古い値で測って合格を出す**という
//   いちばん困る壊れ方をする。
